// Generates src/data/market-to-iso.ts from the "Multipliers" sheet of the
// reference workbook. That sheet maps every ISO 3166-1 country to Meta's
// rate card market, following Meta's country-calling-codes page:
// https://developers.facebook.com/docs/whatsapp/pricing#country-calling-codes
//
// Usage: npm run build:market-map [path/to/max-price-multipliers.xlsx]
import { readFileSync, writeFileSync } from 'node:fs';
import * as XLSX from 'xlsx';

const src = process.argv[2] ?? 'data/max-price-multipliers-eur.xlsx';
const wb = XLSX.read(readFileSync(src));
const rows = XLSX.utils.sheet_to_json<Record<string, unknown>>(wb.Sheets['Multipliers']);

const SHARED = /^Shares a calling code with (.+?): may bill as (.+?) or (.+?);/;

const entries = rows.map((r) => {
  const iso = String(r['ISO']);
  const name = String(r['Country']);
  const note = String(r['Note'] ?? '');
  const shared = note.match(SHARED);
  // Territories sharing a calling code with a named market may be billed as
  // either; keep both candidates so the calculator can pick the cheaper one
  // for whatever currency's rate card is loaded.
  const markets = shared ? [shared[2], shared[3]] : [String(r['Rate card market'])];
  return { iso, name, markets };
});

entries.sort((a, b) => a.iso.localeCompare(b.iso));

const body = entries
  .map((e) => `  ${e.iso}: { name: ${JSON.stringify(e.name)}, markets: ${JSON.stringify(e.markets)} },`)
  .join('\n');

const out = `// GENERATED by scripts/build-market-map.ts from ${src.split('/').pop()} ("Multipliers" sheet).
// Source of the mapping: Meta, https://developers.facebook.com/docs/whatsapp/pricing#country-calling-codes
// Every ISO 3166-1 alpha-2 country -> the rate card market(s) Meta may bill it as.
// One market: the named market, or "Other" when Meta does not name the country.
// Two markets: the country shares a calling code with a named market and may be
// billed as either; the calculator uses the lower rate.

export interface CountryMarket {
  name: string;
  markets: string[];
}

export const OTHER_MARKET = 'Other';

export const COUNTRY_MARKETS: Record<string, CountryMarket> = {
${body}
};
`;

writeFileSync('src/data/market-to-iso.ts', out);
console.log(`Wrote ${entries.length} countries to src/data/market-to-iso.ts`);
